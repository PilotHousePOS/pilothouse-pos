#!/usr/bin/env node
// ─── PilotHouse — Electron pre-build: bake SERVER_URL into a constants file ──
//
// Run automatically as part of `npm run build:electron:main`.
// Reads PILOTHOUSE_SERVER_URL from the environment (set in GitHub Actions
// secrets or locally) and writes electron/env-constants.ts so that tsc can
// compile the value directly into the packaged binary.
//
// If the variable is not set, falls back to the production default so that
// a local build without the secret still produces a usable installer.

import { writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));

const DEFAULT_URL = 'https://pilothouse.replit.app';
const serverUrl = (process.env.PILOTHOUSE_SERVER_URL ?? '').trim() || DEFAULT_URL;

// Validate that it looks like an absolute URL before baking it in
if (!serverUrl.startsWith('http://') && !serverUrl.startsWith('https://')) {
  console.error(
    `[write-electron-env] ERROR: PILOTHOUSE_SERVER_URL must be an absolute URL, got: "${serverUrl}"`
  );
  process.exit(1);
}

const outPath = resolve(__dirname, '../electron/env-constants.ts');

const content = `// AUTO-GENERATED by scripts/write-electron-env.js — do not edit manually.
// Regenerated on every \`npm run build:electron:main\` run.
// Source: PILOTHOUSE_SERVER_URL env var (falls back to the production default).

export const BAKED_SERVER_URL = '${serverUrl}';
`;

writeFileSync(outPath, content, 'utf8');
console.log(`[write-electron-env] Baked SERVER_URL → ${serverUrl}`);
